"use client";

import { useState } from "react";
import { aiOpportunitiesRuleDisplay } from "../lib/autopilot-strategy-presentation";
import { ACTIVE_RESEARCH_MODEL } from "../lib/annual-core-policy";

type ExplainerVariant = "autopilot" | "opportunity-selection";

const AUTOPILOT_STEPS = [
  ["Research AI-related companies", "Assess how each company shapes or applies AI, alongside financial health, growth and risk."],
  ["Check eligibility", "Identify companies that meet the evidence and market checks."],
  ["Build the portfolio", "Choose how much to allocate to each company within the portfolio limits."],
  ["Review and update", "Record hypothetical buys and sells when the research and portfolio rules call for a change."],
] as const;

export type AutopilotRuleInputs = {
  qualifyingOpportunityCount: number | null;
  maxPositionPercent: number | null;
  maxPositions: number | null;
};

function rulePercent(value: number) {
  return `${Math.round(value * 100)}%`;
}

export function VeyroExplainer({
  variant,
  currentRules = null,
  simulationStartedAt,
}: {
  variant: ExplainerVariant;
  currentRules?: AutopilotRuleInputs | null;
  simulationStartedAt?: string;
}) {
  const [expanded, setExpanded] = useState(false);
  if (variant === "opportunity-selection") {
    return (
      <section className="opportunity-selection-explainer" aria-labelledby="opportunity-selection-title">
        <h2 id="opportunity-selection-title">How companies are assessed</h2>
        <p>Veyro assesses how companies shape or apply AI, alongside financial health, growth, valuation, evidence quality and risk.</p>
      </section>
    );
  }

  const rules = aiOpportunitiesRuleDisplay({
    ...(currentRules ?? {
      qualifyingOpportunityCount: null,
      maxPositionPercent: null,
      maxPositions: null,
    }),
    balancedPolicy: ACTIVE_RESEARCH_MODEL,
  });
  const cashReserveLimit = rules.effectiveCashReservePercent === null
    ? "Unavailable"
    : rules.effectiveCashReservePercent === 0
      ? "No mandatory reserve"
      : `Keep at least ${rulePercent(rules.effectiveCashReservePercent)} available`;
  return (
    <section className="autopilot-how-it-works" aria-label="Portfolio simulation explanation">
      <p className="autopilot-summary-line">Explore an offline synthetic ledger generated by Veyro’s simulation engine. Scheduling is paused; no real money is invested.</p>
      <button
        type="button"
        className="autopilot-disclosure-toggle"
        aria-expanded={expanded}
        aria-controls="autopilot-how-it-works-panel"
        onClick={() => setExpanded((current) => !current)}
      >
        <span>How the simulation works</span>
        <span className="autopilot-disclosure-chevron" aria-hidden="true">›</span>
      </button>
      <div
        id="autopilot-how-it-works-panel"
        className="autopilot-disclosure-panel"
        hidden={!expanded}
      >
        {simulationStartedAt ? <p>Simulation started {new Intl.DateTimeFormat("en-NZ", { day: "numeric", month: "short", year: "numeric", timeZone: "America/New_York" }).format(new Date(simulationStartedAt))}</p> : null}
        <ol className="explainer-steps">
          {AUTOPILOT_STEPS.map(([title, description], index) => (
            <li className="explainer-step" key={title}>
              <span className="explainer-step-number" aria-hidden="true">{index + 1}</span>
              <span>
                <strong>{title}</strong>
                <small>{description}</small>
              </span>
            </li>
          ))}
        </ol>
        <p>Simulated results do not predict future returns or guarantee real trading results.</p>
        <p>New buys and additions require positive net profit or positive free cash flow and passing financial and risk checks. There is no minimum research score for purchases. Revenue growth contributes 50% of the research score, with no separate growth minimum or growth-based exit. Missing or stale growth requires review. A holding is sold when its verified current Research rank falls outside the Top 15. One verified assessment is sufficient. Missing, stale or invalid scoring evidence protects holdings from ranking exits. New buys and additions are limited to the Top 15 and still need the other purchase checks. Holdings within the Top 15 are not sold just because another company scores higher. Explicit research-risk exits still apply. Purchase targets are 15% for scores of 75 or higher, 12% for scores from 65 to below 75, and 10% for scores below 65, scaled down when available capital requires it. Holdings above their purchase target receive no additions. Price appreciation alone does not trigger a sale.</p>
        <div className="autopilot-portfolio-limits">
          <h2>Portfolio limits</h2>
          <dl>
            <div>
              <dt>Cash reserve</dt>
              <dd>{cashReserveLimit}</dd>
            </div>
            <div>
              <dt>Purchase sizing ceiling</dt>
              <dd>{rules.maxPositionPercent === null ? "Unavailable" : `Up to ${rulePercent(rules.maxPositionPercent)}`}</dd>
            </div>
            <div>
              <dt>Theme exposure</dt>
              <dd>No theme limit</dd>
            </div>
            <div>
              <dt>Portfolio size</dt>
              <dd>{rules.maxPositions === null ? "Unavailable" : `Up to ${rules.maxPositions} companies`}</dd>
            </div>
          </dl>
          <p>Up to 100% can be invested when qualifying purchase targets allow it. Cash remains when there are fewer opportunities or purchases are below the minimum size.</p>
        </div>
      </div>
    </section>
  );
}
